package com.example.alakzatjavafx260911;

public class Alakzat {
    private String szin;
    private String alakzat;

    public Alakzat(String szin, String alakzat) {
        this.szin = szin;
        this.alakzat = alakzat;
    }

    public String getSzin() {
        return szin;
    }

    public String getAlakzat() {
        return alakzat;
    }
}
